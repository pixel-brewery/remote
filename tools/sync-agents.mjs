// #region Imports

import { lstat, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// #endregion

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const markdownMarker = '<!-- Generated by yarn agents:sync. Edit the canonical agent sources. -->';
const tomlMarker = '# Generated by yarn agents:sync. Edit the canonical agent sources.';
const roleNames = ['architect', 'designer'];

async function statIfPresent(path) {
    try {
        return await lstat(path);
    } catch (error) {
        if (error.code === 'ENOENT') return undefined;
        throw error;
    }
}

async function workspaceFile(root, name) {
    const parts = name.split('/');
    if (parts.some((part) => !part || part === '.' || part === '..' || part.includes('\\'))) {
        throw new Error(`Invalid workspace file: ${name}`);
    }

    let path = root;
    for (const part of parts.slice(0, -1)) {
        path = join(path, part);
        const metadata = await statIfPresent(path);
        if (metadata && !metadata.isDirectory()) {
            throw new Error(`Expected a directory at ${relative(root, path)}`);
        }
    }

    path = join(path, parts.at(-1));
    const metadata = await statIfPresent(path);
    if (metadata && !metadata.isFile()) {
        throw new Error(`Expected a regular file at ${name}`);
    }

    return { path, exists: Boolean(metadata) };
}

async function readWorkspaceText(root, name) {
    const { path } = await workspaceFile(root, name);
    return readFile(path, 'utf8');
}

async function readSources(root) {
    const configuration = JSON.parse(await readWorkspaceText(root, '.agents/config.json'));
    const registry = JSON.parse(await readWorkspaceText(root, '.vscode/mcp.json'));
    const servers = Object.entries(registry.servers ?? {});
    const serverCommands = { mosaik: ['exec', 'mosaik-mcp'], 'nx-mcp': ['nx', 'mcp'] };
    if (servers.length !== Object.keys(serverCommands).length || servers.some(([name, server]) =>
        !Object.hasOwn(serverCommands, name) ||
        Object.keys(server ?? {}).length !== 3 ||
        server.type !== 'stdio' ||
        server.command !== 'yarn' ||
        JSON.stringify(server.args) !== JSON.stringify(serverCommands[name])
    )) {
        throw new Error('.vscode/mcp.json must define the workspace Mosaik and Nx stdio servers.');
    }

    const roles = configuration.roles;
    if (!roles || Object.keys(roles).length !== roleNames.length) {
        throw new Error('.agents/config.json must define architecture and design roles.');
    }

    await readWorkspaceText(root, 'AGENTS.md');
    for (const name of roleNames) {
        const role = roles[name];
        if (
            role?.skill !== `remote-${name}` ||
            typeof role.description !== 'string' ||
            !role.description.trim()
        ) {
            throw new Error(`Invalid ${name} definition in .agents/config.json.`);
        }
        await readWorkspaceText(root, `.agents/skills/${name}/SKILL.md`);
        await readWorkspaceText(root, `.agents/skills/${role.skill}/SKILL.md`);
    }

    const codexSubagents = Object.entries(configuration.codexSubagents ?? {});
    for (const [name, description] of codexSubagents) {
        if (!/^[a-z][a-z0-9-]*$/.test(name) || roleNames.includes(name) ||
            typeof description !== 'string' || !description.trim()) {
            throw new Error(`Invalid Codex subagent definition: ${name}.`);
        }
        await readWorkspaceText(root, `.codex/agents/${name}.toml`);
    }

    return { roles, servers, codexSubagents };
}

function asJson(value) {
    return JSON.stringify(value, null, 4) + '\n';
}

function instructionsFor(roles) {
    return [
        'Read and apply [AGENTS.md](AGENTS.md) for every task.',
        `Follow [Remote Architect](.agents/skills/${roles.architect.skill}/SKILL.md) and its pinned Architecture foundation.`,
        `For UI or design work, follow [Remote Designer](.agents/skills/${roles.designer.skill}/SKILL.md) and its Mosaik catalog workflow.`,
    ].join('\n');
}

function relativeInstructions(path, instructions) {
    const prefix = relative(dirname(path), '.').split(sep).join('/');
    if (!prefix) return instructions;

    return instructions.replaceAll('](', `](${prefix}/`);
}

function agentInstructions(role) {
    return `Read and apply AGENTS.md and .agents/skills/${role.skill}/SKILL.md from the repository root. Follow the linked foundation and references before proposing changes.`;
}

function renderProjections({ roles, servers, codexSubagents }) {
    const instructions = instructionsFor(roles);
    const rootGuide = `${markdownMarker}\n\n${instructions}\n`;
    const projectServers = (project) => Object.fromEntries(
        servers.map(([name, server]) => [name, project(server)]),
    );

    const output = new Map([
        ['CODEX.md', rootGuide],
        ['CLAUDE.md', `${markdownMarker}\n\n@AGENTS.md\n\n${instructions}\n`],
        ['GEMINI.md', rootGuide],
        [
            '.github/copilot-instructions.md',
            `${markdownMarker}\n\n${relativeInstructions('.github/copilot-instructions.md', instructions)}\n`,
        ],
        [
            '.cursor/rules/repository.mdc',
            [
                '---',
                'description: Shared Cursor repository instructions',
                'alwaysApply: true',
                '---',
                '',
                markdownMarker,
                '',
                relativeInstructions('.cursor/rules/repository.mdc', instructions),
                '',
            ].join('\n'),
        ],
        [
            '.codex/config.toml',
            [
                tomlMarker,
                '',
                ...servers.flatMap(([name, { command, args }]) => [
                    `[mcp_servers.${name}]`,
                    `command = ${JSON.stringify(command)}`,
                    `args = ${JSON.stringify(args)}`,
                    'cwd = "."',
                    '',
                ]),
                ...codexSubagents.flatMap(([name, description]) => [
                    `[agents.${name}]`,
                    `description = ${JSON.stringify(description)}`,
                    `config_file = "agents/${name}.toml"`,
                    '',
                ]),
            ].join('\n'),
        ],
        ['.mcp.json', asJson({ mcpServers: { mosaik: Object.fromEntries(servers).mosaik } })],
        [
            'opencode.json',
            asJson({
                $schema: 'https://opencode.ai/config.json',
                instructions: ['AGENTS.md'],
                mcp: projectServers(({ command, args }) => ({
                    type: 'local', command: [command, ...args], enabled: true,
                })),
            }),
        ],
        [
            '.github/mcp.json',
            asJson({ mcpServers: projectServers((server) => ({ ...server, tools: ['*'] })) }),
        ],
        ['.cursor/mcp.json', asJson({ mcpServers: projectServers(({ command, args }) => ({ command, args })) })],
        [
            '.gemini/settings.json',
            asJson({
                context: { fileName: ['AGENTS.md', 'GEMINI.md'] },
                mcpServers: projectServers(({ command, args }) => ({ command, args, cwd: '.' })),
            }),
        ],
    ]);

    for (const name of roleNames) {
        const role = roles[name];
        const description = JSON.stringify(role.description);
        const body = agentInstructions(role);
        const agent = `---\nname: ${name}\ndescription: ${description}\n---\n\n${markdownMarker}\n\n${body}\n`;
        output.set(`.claude/agents/${name}.md`, agent);
        output.set(`.github/agents/${name}.agent.md`, agent);
        output.set(
            `.opencode/agents/${name}.md`,
            `---\ndescription: ${description}\nmode: subagent\n---\n\n${markdownMarker}\n\n${body}\n`,
        );
        output.set(
            `.codex/agents/${name}.toml`,
            `${tomlMarker}\nname = ${JSON.stringify(name)}\ndescription = ${description}\ndeveloper_instructions = ${JSON.stringify(body)}\n`,
        );
        output.set(
            `.claude/skills/${role.skill}/SKILL.md`,
            [
                '---',
                `name: ${role.skill}`,
                `description: ${description}`,
                '---',
                '',
                markdownMarker,
                '',
                `Read the [canonical ${role.skill} skill](../../../.agents/skills/${role.skill}/SKILL.md) in full. Resolve its linked references from the canonical skill's directory.`,
                '',
            ].join('\n'),
        );
    }

    return output;
}

/**
 * Synchronizes the explicitly owned agent projections or reports their drift.
 *
 * @param {{ root?: string, write?: boolean }} options - Workspace and access mode.
 * @returns {Promise<number>} The number of projections.
 */
export async function syncAgents({ root = repository, write = false } = {}) {
    root = resolve(root);
    const output = renderProjections(await readSources(root));
    const differences = [];

    for (const [name, content] of output) {
        const { path, exists } = await workspaceFile(root, name);
        if (!exists || (await readFile(path, 'utf8')) !== content) {
            differences.push({ name, path, content });
        }
    }

    if (differences.length && !write) {
        throw new Error(
            `Generated agent configuration is out of sync. Run yarn agents:sync.\n${differences.map(({ name }) => `- ${name}`).join('\n')}`,
        );
    }

    for (const { path, content } of differences) {
        await mkdir(dirname(path), { recursive: true });
        await writeFile(path, content);
    }

    return output.size;
}

async function main() {
    const args = process.argv.slice(2);
    if (args.length !== 1 || !['--check', '--write'].includes(args[0])) {
        throw new Error('Usage: node tools/sync-agents.mjs --check | --write');
    }
    const count = await syncAgents({ write: args[0] === '--write' });
    process.stdout.write(`Agent configuration is synchronized (${count} generated files).\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    main().catch((error) => {
        process.stderr.write(`${error.message}\n`);
        process.exitCode = 1;
    });
}
