// #region Imports
import { z } from 'zod';
import { remoteHostIdentitySchema } from '../../host/schemas/remoteHostIdentitySchema.js';
// #endregion
/**
 * Versioned private storage contract. Never expose this record in renderer projections.
 *
 * @public
 */
export const remoteAccessStateSchema = z
    .strictObject({
        /**
         * Stored authorization format version. This schema accepts exactly version one.
         *
         * @public
         */
        version: z.literal(1),
        /**
         * Stable application and installation namespace. A record from another installation must fail restoration.
         *
         * @public
         */
        identity: remoteHostIdentitySchema,
        /**
         * Durably saved activation intent. A missing record starts disabled; network availability does not erase this preference.
         *
         * @public
         */
        enabled: z.boolean(),
        /**
         * At most one hundred durable device grants. Pairing challenges and plaintext credentials are never part of this collection.
         *
         * @public
         */
        devices: z
            .array(
                z
                    .strictObject({
                        /**
                         * Stable opaque identifier within the owning endpoint, connection or device collection.
                         *
                         * @public
                         */
                        id: z.string().min(1).max(160),
                        /**
                         * Trimmed human-readable label. It conveys no authorization and must fit the schema character bound.
                         *
                         * @public
                         */
                        name: z.string().trim().min(1).max(120),
                        /**
                         * Digest generated by the injected security port for credential verification. Never store the plaintext bearer here.
                         *
                         * @public
                         */
                        tokenHash: z.string().min(32).max(256),
                        /**
                         * At most 256 named operation capabilities. Each name is nonempty and at most 160 characters; product resource checks remain separate.
                         *
                         * @public
                         */
                        capabilities: z.array(z.string().min(1).max(160)).max(256).readonly(),
                        /**
                         * UTC ISO 8601 instant at which the device grant was durably committed.
                         *
                         * @public
                         */
                        pairedAt: z.iso.datetime(),
                        /**
                         * Optional UTC ISO 8601 last-use instant retained for application migrations or administration.
                         *
                         * @public
                         */
                        lastSeenAt: z.iso.datetime().optional(),
                    })
                    .readonly(),
            )
            .max(100)
            .readonly(),
    })
    .readonly();
