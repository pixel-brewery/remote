// #region Imports
import { describe, expect, it } from 'vitest';
import type { IRemoteRouteDefinition } from '@pixel-brewery/remote-protocol';
import { createRemoteNativeRouteSources } from './createRemoteNativeRouteSources.js';
import type { IRemoteNativeRouteSourceOptions } from './interfaces/IRemoteNativeRouteSourceOptions.js';
// #endregion

const options: IRemoteNativeRouteSourceOptions = {
    appId: 'com.example.notes',
    kotlin: { packageName: 'com.example.notes.remote', objectName: 'NotesRemoteRoutes' },
    swift: { typeName: 'NotesRemoteRoutes' },
};
const routes: readonly IRemoteRouteDefinition[] = [
    {
        id: 'upload',
        method: 'POST',
        path: '/api/notes/:noteId/files',
        kind: 'http',
        capabilities: ['notes:write'],
        retry: 'never',
        maxRequestBytes: 27262976,
    },
    {
        id: 'events',
        method: 'GET',
        path: '/api/events',
        kind: 'sse',
        capabilities: ['notes:read'],
        retry: 'never',
        maxRequestBytes: 0,
    },
    {
        id: 'readNote',
        method: 'GET',
        path: '/api/notes/:noteId',
        kind: 'http',
        capabilities: ['notes:read'],
        retry: 'safe-read',
        maxRequestBytes: 4194304,
    },
];

describe('createRemoteNativeRouteSources', () => {
    it('emits one sorted canonical inventory for JSON, Kotlin and Swift consumers', () => {
        // Arrange / Act
        const sources = createRemoteNativeRouteSources(routes, options);
        const json = JSON.parse(sources.json) as {
            appId: string;
            protocolVersion: number;
            routes: IRemoteRouteDefinition[];
        };
        // Assert
        expect(json.appId).toBe('com.example.notes');
        expect(json.protocolVersion).toBe(1);
        expect(json.routes.map((route) => route.id)).toEqual(['events', 'readNote', 'upload']);
        expect(json.routes[2]).toEqual(routes[0]);
        expect(sources.kotlin).toContain('package com.example.notes.remote\n');
        expect(sources.kotlin).toContain('internal object NotesRemoteRoutes {');
        expect(sources.kotlin).toContain(
            'RemoteNativeConfiguration.Route(id = "upload", method = "POST", path = "/api/notes/:noteId/files", kind = "http", capabilities = setOf("notes:write"), maxRequestBytes = 27262976L),',
        );
        expect(sources.swift).toContain('import RemoteCapacitor\n');
        expect(sources.swift).toContain('internal enum NotesRemoteRoutes {');
        expect(sources.swift).toContain(
            'try .init(id: "events", method: "GET", path: "/api/events", kind: "sse", capabilities: Set(["notes:read"]), maxRequestBytes: 0),',
        );
        for (const text of [sources.json, sources.kotlin, sources.swift])
            expect(text.endsWith('\n')).toBe(true);
        expect(sources.kotlin.startsWith('// Generated by')).toBe(true);
        expect(Object.isFrozen(sources)).toBe(true);
    });

    it('is deterministic under input order and honours an explicit protocol version', () => {
        // Arrange
        const reversed = [...routes].reverse();
        // Act
        const first = createRemoteNativeRouteSources(routes, options);
        const second = createRemoteNativeRouteSources(reversed, options);
        const versioned = createRemoteNativeRouteSources(routes, {
            ...options,
            protocolVersion: 2,
        });
        // Assert
        expect(second).toEqual(first);
        expect(JSON.parse(versioned.json)).toMatchObject({ protocolVersion: 2 });
    });

    it('escapes native literals while the JSON keeps the exact canonical identifier', () => {
        // Arrange
        const id = 'read$quoted' + String.fromCharCode(34, 92, 10, 8, 0x2028);
        const route = { ...routes[2]!, id };
        // Act
        const sources = createRemoteNativeRouteSources([route], options);
        // Assert
        expect((JSON.parse(sources.json) as { routes: Array<{ id: string }> }).routes[0]?.id).toBe(
            id,
        );
        expect(sources.kotlin).toContain('"read\\$quoted\\"\\\\\\n\\u0008\\u2028"');
        expect(sources.swift).toContain('"read$quoted\\"\\\\\\n\\u{8}\\u{2028}"');
        expect(sources.kotlin).not.toContain(id);
        expect(sources.swift).not.toContain(id);
    });

    it('rejects empty, inadmissible and unbounded route sets and unsafe declaration names', () => {
        // Arrange
        const duplicate = { ...routes[2]!, id: 'other', path: '/api/notes/:other' };
        const { maxRequestBytes: _declared, ...unbounded } = routes[2]!;
        const oversized = { ...routes[0]!, maxRequestBytes: 67108865 };
        const invalidOptions: IRemoteNativeRouteSourceOptions[] = [
            { ...options, appId: 'Notes' },
            { ...options, protocolVersion: 0 },
            { ...options, kotlin: { ...options.kotlin, packageName: 'com.example;evil' } },
            { ...options, kotlin: { ...options.kotlin, objectName: 'Routes {}' } },
            { ...options, swift: { typeName: '' } },
        ];
        // Act / Assert
        for (const candidate of [[], [routes[2]!, duplicate], [unbounded], [oversized]])
            expect(() => createRemoteNativeRouteSources(candidate, options)).toThrow(
                expect.objectContaining({ code: 'invalid-request' }),
            );
        for (const candidate of invalidOptions)
            expect(() => createRemoteNativeRouteSources(routes, candidate)).toThrow(
                expect.objectContaining({ code: 'invalid-request' }),
            );
    });
});
